// QA: every holiday's shopping list (shared/seasonal.js) against real product names.
//
// For each item on every occasion's list, test/fixtures/holiday-matrix.json holds names a shopper
// would expect that search to find ("match") and look-alikes it must not be answered with
// ("reject"): baking soda for "soda", cooking wine for "wine", Cadbury Creme Eggs for "eggs",
// celery salt for "celery", Reese's cups for "peanut butter". When this table was first written,
// 63 of its 305 cases failed: 21 look-alikes that could win a holiday list's headline price and 42
// real products (red wine, beef brisket, Ball Park franks, Stove Top) hidden from it.
//
// The same fixture drives ios/Tests/HolidayMatrixTests.swift (generated by
// scripts/gen-ios-holiday-tests.js), so the phone is held to the same cases.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { relevance, RELEVANT } from '../shared/match.js';
import { OCCASIONS } from '../shared/seasonal.js';

const TABLE = JSON.parse(fs.readFileSync(new URL('./fixtures/holiday-matrix.json', import.meta.url), 'utf8'));

import { execFileSync } from 'node:child_process';
test('the iOS holiday XCTests are generated from this fixture', () => {
  execFileSync(process.execPath, [new URL('../scripts/gen-ios-holiday-tests.js', import.meta.url).pathname, '--check']);
});

test('every item on every holiday list has cases', () => {
  const have = new Set(TABLE.map((r) => r.query));
  const missing = [...new Set(OCCASIONS.flatMap((o) => o.list))].filter((i) => !have.has(i));
  assert.deepEqual(missing, []);
});

for (const o of OCCASIONS) {
  test(`${o.name}: every list item finds the real product and not the look-alike`, () => {
    const wrong = [];
    for (const q of o.list) {
      const row = TABLE.find((r) => r.query === q);
      for (const n of row.match) { const s = relevance(q, { name: n }); if (s < RELEVANT) wrong.push(`hidden  ${s.toFixed(2)} "${q}" | ${n}`); }
      for (const n of row.reject) { const s = relevance(q, { name: n }); if (s >= RELEVANT) wrong.push(`matched ${s.toFixed(2)} "${q}" | ${n}`); }
    }
    assert.deepEqual(wrong, []);
  });
}
